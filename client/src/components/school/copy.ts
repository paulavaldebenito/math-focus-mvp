export type SchoolCopy = (typeof SCHOOL)["es"];

export const pct = (x: number) => `${Math.round(x * 100)} %`;
export const guarded = (g: Guarded<number>, c: SchoolCopy) => (g.ok ? pct(g.value) : c.fewData);

/// "OA 11" a partir de "MA03 OA11" (cabecera corta del mapa de calor).
export const oaShort = (s: SchoolSkill) => (s.oaCode ? s.oaCode.replace(/^MA0\d\s*/, "").replace("OA", "OA ") : s.name.slice(0, 8));
export const oaLabel = (s: SchoolSkill | undefined, lang: Lang) => (s ? `${s.oaCode ?? ""} ${localize(lang, s.name, s.nameEn)}`.trim() : "");

