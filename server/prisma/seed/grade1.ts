import { block, type ErrorIds, type SeedExercise, type SkillBlock } from "./lib.js";

type ErrCode = "E1_OP" | "E2_RES" | "E2_CAL" | "E3_PREG" | "E3_DATO";
type Wrong = [label: string, code: ErrCode];

/// Ejercicio de opción múltiple sin visual: la correcta primero, cada
/// distractor con su código de error. Texto: [enunciado, pista].
function mk(
  e: ErrorIds,
  level: number,
  es: [string, string],
  en: [string, string],
  correct: string,
  wrong: Wrong[],
): SeedExercise {
  return {
    prompt: es[0],
    promptEn: en[0],
    procedureNote: es[1],
    procedureNoteEn: en[1],
    difficultyLevel: level,
    visual: null,
    options: [
      { label: correct, isCorrect: true },
      ...wrong.map(([label, code]) => ({ label, isCorrect: false, errorTypeId: e[code] })),
    ],
  };
}

/// Secuencia numérica "a, b, c" con `count` términos.
const seq = (start: number, step: number, count: number): string =>
  Array.from({ length: count }, (_, i) => start + step * i).join(", ");
/// Término que sigue tras `count` términos mostrados.
const nextTerm = (start: number, step: number, count: number): number => start + step * count;

