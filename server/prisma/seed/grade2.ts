type ErrCode = "E1_OP" | "E2_RES" | "E2_CAL" | "E3_PREG" | "E3_DATO";

// Constructor compacto para los bloques nuevos: la correcta va primero y
// cada distractor lleva su código de error.
function mkEx(
  e: ErrorIds,
  level: 1 | 2 | 3,
  prompt: string,
  promptEn: string,
  procedureNote: string,
  procedureNoteEn: string,
  correct: string,
  wrong: Array<[string, ErrCode]>,
): SeedExercise {
  return {
    prompt,
    promptEn,
    procedureNote,
    procedureNoteEn,
    difficultyLevel: level,
    visual: null,
    options: [
      { label: correct, isCorrect: true },
      ...wrong.map(([label, code]) => ({ label, isCorrect: false, errorTypeId: e[code] })),
    ],
  };
}

