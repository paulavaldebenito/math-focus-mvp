const gcd = (a: number, b: number): number => (b === 0 ? a : gcd(b, a % b));

/// Fracción simplificada "n/d" (o entero si d = 1).
function fr(n: number, d: number): string {
  const g = gcd(n, d);
  return d / g === 1 ? String(n / g) : `${n / g}/${d / g}`;
}

/// Número mixto simplificado "E n/d" a partir de una fracción impropia.
function mixed(n: number, d: number): string {
  const g = gcd(n, d);
  const nn = n / g;
  const dd = d / g;
  const whole = Math.floor(nn / dd);
  const rem = nn % dd;
  if (rem === 0) return String(whole);
  return whole === 0 ? `${rem}/${dd}` : `${whole} ${rem}/${dd}`;
}

/// Separador de miles chileno (punto): 60000 -> "60.000".
function miles(x: number): string {
  return String(Math.round(x)).replace(/\B(?=(\d{3})+(?!\d))/g, ".");
}

