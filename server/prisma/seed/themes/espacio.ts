// Variantes temáticas del interés "espacio": naves, cohetes, astronautas, estaciones,
// planetas, lunas, estrellas, telescopios, cápsulas y misiones. Solo contexto de
// historia: no se afirma ningún dato astronómico concreto.

type Row = [base: string, prompt: string, promptEn: string, note: string, noteEn: string, emoji?: string];

function mk(grade: number, skill: string, rows: Row[]): ThemedVariant[] {
  return rows.map(([base, prompt, promptEn, procedureNote, procedureNoteEn, emoji]) => ({
    grade,
    skill,
    base,
    prompt,
    promptEn,
    procedureNote,
    procedureNoteEn,
    ...(emoji ? { emoji } : {}),
  }));
}

