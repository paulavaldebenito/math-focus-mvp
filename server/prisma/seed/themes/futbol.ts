/// Atajo para escribir cada variante: [enunciado, enunciado EN], [pista, pista EN].
function v(
  grade: number,
  skill: string,
  base: string,
  text: [string, string],
  note: [string, string],
  emoji?: string,
): ThemedVariant {
  return {
    grade,
    skill,
    base,
    prompt: text[0],
    promptEn: text[1],
    procedureNote: note[0],
    procedureNoteEn: note[1],
    ...(emoji ? { emoji } : {}),
  };
}

